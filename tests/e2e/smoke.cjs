// Browser walkthrough against a running preview build (npm run build && npm run preview).
// Run: OUT=./shots node tests/e2e/smoke.cjs   (DARK=1 for dark theme). Requires Playwright + Chromium.
// Note: uses the real clock (Asia/Dhaka). Prints NO ERRORS on success.
const { chromium } = require('playwright');
const OUT = process.env.OUT;
const URL = 'http://localhost:4173/';
const errors = [];
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 1, colorScheme: process.env.DARK ? 'dark' : 'light' });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  p.on('console', (m) => m.type() === 'error' && errors.push('console: ' + m.text()));
  const shot = async (n) => { await p.waitForTimeout(400); await p.screenshot({ path: `${OUT}/${n}.png`, fullPage: true }); };
  const overflow = async (n) => { const w = await p.evaluate(() => document.documentElement.scrollWidth); if (w > 375) errors.push(`horizontal overflow on ${n}: ${w}px`); };
  await p.goto(URL);
  await p.waitForSelector('text=Your O Level study hub');
  await shot('01-setup'); await overflow('setup');
  await p.click('text=Continue');
  await shot('02-setup-time');
  await p.click('text=Continue');
  await p.fill('input[aria-label="Commitment name"]', 'Physics tutor');
  await p.click('button:has-text("Add")');
  await p.click('text=Create my plan');
  await p.waitForSelector('text=Up next', { timeout: 10000 });
  await shot('03-today'); await overflow('today');
  // Start session
  await p.click('text=Start session');
  await p.waitForSelector('text=How much can you give today?');
  await shot('04-session-mode');
  await p.click('[role=radio]:has-text("Steady")');
  await p.waitForSelector('button:has-text("Done")');
  await shot('05-session-active'); await overflow('session');
  for (let i = 0; i < 6; i++) { const d = p.locator('button:has-text("Done")'); if (await d.count()) await d.first().click(); await p.waitForTimeout(150); }
  await p.waitForSelector('text=All activities done');
  await p.click('text=Finish session');
  await p.waitForSelector('text=Session complete');
  await shot('06-summary');
  await p.click('text=Record your score');
  await p.waitForSelector('text=Record a result');
  await p.fill('input[aria-label="Marks earned"]', '4');
  await p.fill('input[aria-label="Marks available"]', '10');
  await p.click('[role=radio]:has-text("Confident")');
  await shot('07-assess');
  await p.click('text=Close').catch(()=>{}); await p.click('text=Save result');
  await p.waitForSelector('text=Marking and correction');
  await shot('08-marking');
  await p.click('text=Skip for now');
  await p.goto(URL + '#/');
  await p.waitForSelector('text=sessions completed');
  await shot('09-today-after');
  // reload persistence
  await p.reload();
  await p.waitForSelector('text=1 of');
  // Schedule
  await p.click('nav.fixed >> text=Schedule');
  await p.waitForSelector('text=completed');
  await shot('10-schedule-week'); await overflow('schedule');
  await p.click('[role=radio]:has-text("Month")');
  await shot('11-schedule-month');
  await p.click('nav.fixed >> text=Subjects');
  await shot('12-subjects');
  await p.click('text=Bangla');
  await p.click('text=Add topics');
  await p.fill('textarea', '১ | পাঠ্যাংশ: বোধগম্যতা\n২ | ব্যাকরণ: সমাস ও সন্ধি\n৩ | রচনা — একটি দীর্ঘ শিরোনাম যা মোবাইলে মোড়ানো উচিত এবং কোনো অনুভূমিক স্ক্রল হওয়া উচিত নয়');
  await p.click('.animate-sheet >> button:has-text("Add topics")');
  await p.waitForSelector('text=added');
  await p.keyboard.press('Escape');
  await shot('13-subject-bangla'); await overflow('subject-bangla');
  await p.click('nav.fixed >> text=Progress');
  await shot('14-progress'); await overflow('progress');
  await p.click('nav.fixed >> text=Review');
  await p.click('[role=radio]:has-text("Repairs")');
  await shot('15-review-repairs');
  await p.click('text=Find what was difficult');
  await p.click('text=Conceptual misunderstanding');
  await shot('16-repair');
  await p.click('text=Use this method');
  await p.goto(URL + '#/exams');
  await p.click('text=Add paper');
  await p.selectOption('.animate-sheet select >> nth=0', 'chemistry');
  await p.fill('input[list=paper-names]', 'Paper 2');
  await p.fill('input[type=date]', '2026-11-30');
  await p.fill('input[type=time]', '09:00');
  await p.click('.animate-sheet >> button:has-text("Save")');
  await p.waitForSelector('text=Plan updated');
  await p.keyboard.press('Escape');
  await shot('17-exams');
  await p.click('[role=radio]:has-text("Home mocks")');
  await p.waitForSelector('text=Suggested Mock 2 series');
  await p.click('button:has-text("Book these")');
  await p.waitForSelector('text=papers booked');
  await shot('17b-home-mocks'); await overflow('home-mocks');
  await p.goto(URL + '#/schedule');
  await p.click('button[aria-label="Next"]');
  await shot('17c-schedule-mock-week');
  await p.goto(URL + '#/settings');
  await p.click('text=Load sample data');
  await p.waitForSelector('text=Sample data is showing');
  await shot('18-settings');
  await p.goto(URL + '#/review');
  await shot('19-review-demo');
  await p.goto(URL + '#/progress');
  await shot('20-progress-demo');
  await p.goto(URL + '#/settings');
  await p.click('text=Clear sample data');
  await p.waitForTimeout(800);
  const banner = await p.locator('text=Sample data is showing').count();
  if (banner) errors.push('demo banner still visible after clear');
  // offline: SW
  await p.goto(URL);
  await p.evaluate(() => navigator.serviceWorker.ready);
  await p.reload();
  await p.waitForFunction(() => !!navigator.serviceWorker.controller, null, { timeout: 15000 });
  await ctx.setOffline(true);
  await p.reload();
  const ok = await p.waitForSelector('text=sessions completed', { timeout: 8000 }).then(() => 1, () => 0);
  if (!ok) errors.push('offline reload failed');
  await shot('21-offline');
  console.log(errors.length ? errors.join('\n') : 'NO ERRORS');
  await b.close();
})().catch((e) => { console.log('FAILED', e.message, errors.join('\n')); process.exit(1); });
